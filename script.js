/* =========================================
   APPLY LANGUAGE
========================================= */

function setLanguage(lang) {

    const t = translations[lang];
    const e = getLanguageElements();

    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";

    document.title = t.pageTitle;

    Object.keys(e).forEach(key => {

        if (!e[key] || !t[key]) {
            return;
        }

        if (e[key] instanceof NodeList) {
            e[key].forEach((element, index) => {

                if (Array.isArray(t[key])) {
                    element.innerHTML = t[key][index];
                }

            });

            return;
        }

        if (key === "profileAlt") {
            e[key].alt = t[key];
            return;
        }

        e[key].innerHTML = t[key];
    });


    /* Update language button */

    const languageButton = document.getElementById("languageSwitcher");

    if (languageButton) {
        languageButton.textContent = lang === "fa" ? "EN" : "FA";
        languageButton.setAttribute(
            "aria-label",
            lang === "fa" ? "Switch to English" : "تغییر به فارسی"
        );
    }


    localStorage.setItem("siteLanguage", lang);
}


/* =========================================
   CREATE LANGUAGE BUTTON
========================================= */

function createLanguageButton() {

    const nav = document.querySelector(".nav");

    if (!nav || document.getElementById("languageSwitcher")) {
        return;
    }

    const button = document.createElement("button");

    button.id = "languageSwitcher";
    button.type = "button";
    button.className = "language-switcher";
    button.textContent = "EN";

    button.addEventListener("click", () => {

        const currentLanguage =
            document.documentElement.lang === "en" ? "en" : "fa";

        const newLanguage =
            currentLanguage === "fa" ? "en" : "fa";

        setLanguage(newLanguage);

    });

    /*
       دکمه قبل از منوی موبایل قرار می‌گیرد.
    */

    nav.insertBefore(button, document.querySelector(".menu-btn"));
}


/* =========================================
   MOBILE MENU
========================================= */

const menuBtn = document.getElementById("menuBtn");
const menu = document.querySelector(".menu");

if (menuBtn && menu) {

    menuBtn.addEventListener("click", () => {
        menu.classList.toggle("active");
    });

}


document.querySelectorAll(".menu a").forEach(link => {

    link.addEventListener("click", () => {

        if (menu) {
            menu.classList.remove("active");
        }

    });

});


/* =========================================
   VIDEO MODAL
========================================= */

const videoModal = document.getElementById("videoModal");
const studentVideo = document.getElementById("studentVideo");


function openVideo(videoPath) {

    studentVideo.src = videoPath;

    videoModal.classList.add("active");

    studentVideo.play();

}


function closeVideo() {

    studentVideo.pause();

    studentVideo.currentTime = 0;

    studentVideo.src = "";

    videoModal.classList.remove("active");

}


if (videoModal) {

    videoModal.addEventListener("click", (event) => {

        if (event.target === videoModal) {
            closeVideo();
        }

    });

}


/* =========================================
   ESC
========================================= */

document.addEventListener("keydown", (event) => {

    if (event.key === "Escape") {
        closeVideo();
    }

});


